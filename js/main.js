const currentLang = document.getElementById("currentLang");
const dropdown = document.getElementById("langDropdown");
const flag = document.getElementById("langFlag");
const text = document.getElementById("langText");

const logoImg = document.querySelector(".logo-img");

const logos = {
    es: "/images/Logo_ES.png",
    en: "/images/Logo_EN.png"
};

const footerLogoImg = document.querySelector(".footer-logo");

function setLanguage(lang) {
    document.querySelectorAll("[data-i18n]").forEach(el => {
        el.innerHTML = translations[lang][el.dataset.i18n];
    });

        if (logoImg && logos[lang]) {
        logoImg.src = logos[lang];
    }

    if (footerLogoImg && logos[lang]) {
  footerLogoImg.src = logos[lang];
}

    if (lang === "es") {
        flag.src = "/images/Bandera_de_España.svg.png";
        text.textContent = "ES";
    } else {
        flag.src = "/images/Flag_of_the_United_Kingdom_(3-5).svg.png";
        text.textContent = "EN";
    }

    localStorage.setItem("lang", lang);
}

currentLang.addEventListener("click", e => {
    e.stopPropagation();
    dropdown.style.display =
        dropdown.style.display === "block" ? "none" : "block";
});

dropdown.querySelectorAll("li").forEach(item => {
    item.addEventListener("click", () => {
        setLanguage(item.dataset.lang);
        dropdown.style.display = "none";
    });
});

document.addEventListener("click", () => {
    dropdown.style.display = "none";
});

setLanguage(localStorage.getItem("lang") || "es");
document.querySelectorAll(".accordion-header").forEach(header => {
    header.addEventListener("click", () => {
        const item = header.parentElement;
        const icon = header.querySelector(".icon");

        // Cerrar otros
        document.querySelectorAll(".accordion-item").forEach(i => {
            if (i !== item) {
                i.classList.remove("open");
                i.querySelector(".icon").textContent = "+";
            }
        });

        // Toggle actual
        item.classList.toggle("open");
        icon.textContent = item.classList.contains("open") ? "−" : "+";
    });
});

const galleryItems = document.querySelectorAll(".gallery-item");
const lightbox = document.getElementById("lightbox");
const lightboxImg = document.getElementById("lightboxImg");
const closeBtn = document.getElementById("lightboxClose");
const prevBtn = document.getElementById("prev");
const nextBtn = document.getElementById("next");

if (galleryItems.length && lightbox && lightboxImg && closeBtn && prevBtn && nextBtn) {
  let currentIndex = 0;

  galleryItems.forEach((img, index) => {
    img.addEventListener("click", () => {
      currentIndex = index;
      lightboxImg.src = img.src;
      lightbox.style.display = "flex";
    });
  });

  closeBtn.addEventListener("click", () => {
    lightbox.style.display = "none";
  });

  prevBtn.addEventListener("click", () => {
    currentIndex = (currentIndex - 1 + galleryItems.length) % galleryItems.length;
    lightboxImg.src = galleryItems[currentIndex].src;
  });

  nextBtn.addEventListener("click", () => {
    currentIndex = (currentIndex + 1) % galleryItems.length;
    lightboxImg.src = galleryItems[currentIndex].src;
  });
}



let currentIndex = 0;

galleryItems.forEach((img, index) => {
    img.addEventListener("click", () => {
        currentIndex = index;
        showImage();
        lightbox.style.display = "flex";
    });
});

function showImage() {
    lightboxImg.src = galleryItems[currentIndex].src;
}

closeBtn.addEventListener("click", () => {
    lightbox.style.display = "none";
});

prevBtn.addEventListener("click", () => {
    currentIndex =
        (currentIndex - 1 + galleryItems.length) % galleryItems.length;
    showImage();
});

nextBtn.addEventListener("click", () => {
    currentIndex = (currentIndex + 1) % galleryItems.length;
    showImage();
});

/* Cerrar al hacer click fuera */
lightbox.addEventListener("click", e => {
    if (e.target === lightbox) {
        lightbox.style.display = "none";
    }
});

/* Teclado */
document.addEventListener("keydown", e => {
    if (lightbox.style.display === "flex") {
        if (e.key === "ArrowRight") nextBtn.click();
        if (e.key === "ArrowLeft") prevBtn.click();
        if (e.key === "Escape") closeBtn.click();
    }
});

